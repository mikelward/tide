#!/usr/bin/env node
// Builds cities.tsv, the Appearance page's cities for sunrise and sunset
// (SPEC.md §16), from GeoNames' cities5000.txt, admin1CodesASCII.txt and
// countryInfo.txt, from https://download.geonames.org/export/dump/:
//
//   node shell/cities/generate.mjs CITIES ADMIN1 COUNTRIES > shell/cities/cities.tsv
//
// It keeps every city of 100,000 people or more, every capital, of a
// country or of its first-level regions, whatever its size, and a few
// towns far north and south, where sunrise and sunset swing furthest. Each line is
// NAME, ASCII, REGION, COUNTRY, LATITUDE, LONGITUDE and POPULATION,
// tab-separated, after a header of `#` lines, most people first. ASCII is
// GeoNames' plain spelling ("Tromso" for "Tromsø"), empty when it's the
// same. Coordinates have two decimals, about a kilometer, which moves
// sunrise by seconds. tide for macOS copies the file unchanged.

import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export const MIN_POPULATION = 100000;
// A country's capital, a first-level region's, and a seat of government
// that isn't the capital.
export const CAPITALS = Object.freeze(["PPLC", "PPLA", "PPLG"]);
// Towns past the Arctic Circle or near Cape Horn that neither rule
// reaches, by GeoNames ID: Fairbanks, Alta, Hammerfest, Kiruna, Narvik,
// Vorkuta and Río Grande (Tierra del Fuego).
export const FAR = Object.freeze(["5861897", "847633", "779683", "605155", "3144987", "1486910", "3838854"]);

export const HEADER = [
    "# Cities for sunrise and sunset (tide SPEC.md §16): name, ASCII name,",
    "# region, country, latitude, longitude, population.",
    "# Generated by shell/cities/generate.mjs from GeoNames' cities5000.txt,",
    "# admin1CodesASCII.txt and countryInfo.txt. Don't edit; regenerate.",
    "# Data: GeoNames (https://www.geonames.org/), CC BY 4.0",
    "# (https://creativecommons.org/licenses/by/4.0/).",
];

// Tab-separated rows, comments and blank lines left out.
function rows(text) {
    return text.split("\n").filter((l) => l !== "" && !l.startsWith("#")).map((l) => l.split("\t"));
}

// admin1CodesASCII.txt as a Map from "CC.CODE" to the region's name.
export function parseRegions(text) {
    return new Map(rows(text).map((f) => [f[0], f[1]]));
}

// countryInfo.txt as a Map from the ISO code to the country's name.
export function parseCountries(text) {
    return new Map(rows(text).map((f) => [f[0], f[4]]));
}

function field(s) {
    return String(s ?? "").replace(/[\t\n\r]/g, " ").trim();
}

// The cities to keep from cities5000.txt, as {name, ascii, region,
// country, latitude, longitude, population}, most people first, then by
// name.
export function pickCities(text, regions, countries) {
    const out = [];
    for (const f of rows(text)) {
        if (f.length < 15) {
            throw new Error(`cities: a line has ${f.length} fields, not 19: ${f[0]}`);
        }
        const population = Number(f[14]) || 0;
        if (population < MIN_POPULATION && !CAPITALS.includes(f[7]) && !FAR.includes(f[0])) {
            continue;
        }
        const latitude = Number(f[4]);
        const longitude = Number(f[5]);
        if (!Number.isFinite(latitude) || !Number.isFinite(longitude)) {
            throw new Error(`cities: ${f[1]} (${f[0]}) has no coordinates`);
        }
        const name = field(f[1]);
        const ascii = field(f[2]);
        out.push({
            name,
            ascii: ascii === name ? "" : ascii,
            region: field(regions.get(`${f[8]}.${f[10]}`)),
            country: field(countries.get(f[8]) ?? f[8]),
            latitude: latitude.toFixed(2),
            longitude: longitude.toFixed(2),
            population,
        });
    }
    out.sort((a, b) => b.population - a.population || (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
    return out;
}

export function citiesTsv(cities) {
    const lines = cities.map((c) => [c.name, c.ascii, c.region, c.country, c.latitude, c.longitude, c.population].join("\t"));
    return HEADER.concat(lines).join("\n") + "\n";
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    const [citiesPath, admin1Path, countriesPath] = process.argv.slice(2);
    if (!countriesPath) {
        console.error("usage: generate.mjs CITIES ADMIN1 COUNTRIES > cities.tsv");
        process.exit(2);
    }
    const regions = parseRegions(readFileSync(admin1Path, "utf8"));
    const countries = parseCountries(readFileSync(countriesPath, "utf8"));
    process.stdout.write(citiesTsv(pickCities(readFileSync(citiesPath, "utf8"), regions, countries)));
}
