#!/usr/bin/env node
// Builds chars.tsv, the picker's Characters tab (SPEC.md §8.4), from
// Unicode's emoji-test.txt and UnicodeData.txt:
//
//   node shell/chars/generate.mjs EMOJI_TEST UNICODE_DATA > shell/chars/chars.tsv
//
// Each line is CHARACTER, NAME and GROUP, tab-separated, after a header of
// `#` lines. Names are lowercase and ASCII, so a search needn't fold
// accents: the emoji by their CLDR short names, without skin-tone
// variants; the symbols by their Unicode names, from the blocks below.
// tilemo copies the file unchanged.

import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

// The symbol blocks, as [first, last, group]. A code point that is also
// an emoji is listed once, as the emoji.
export const BLOCKS = Object.freeze([
    [0x00a1, 0x00ff, "Latin-1"],
    [0x0100, 0x017f, "Latin Extended-A"],
    [0x0391, 0x03c9, "Greek"],
    [0x2010, 0x205e, "Punctuation"],
    [0x2070, 0x209c, "Superscripts and subscripts"],
    [0x20a0, 0x20c0, "Currency"],
    [0x2100, 0x214f, "Letterlike"],
    [0x2150, 0x218b, "Number forms"],
    [0x2190, 0x21ff, "Arrows"],
    [0x2200, 0x22ff, "Math"],
    [0x2300, 0x23ff, "Technical"],
    [0x25a0, 0x25ff, "Shapes"],
    [0x2600, 0x26ff, "Miscellaneous symbols"],
    [0x2700, 0x27bf, "Dingbats"],
    [0x27f0, 0x27ff, "Arrows"],
    [0x2900, 0x297f, "Arrows"],
]);

// Lowercase ASCII: accents dropped, curly quotes straightened.
export function plainName(name) {
    return name.normalize("NFKD")
        .replace(/[̀-ͯ]/g, "")
        .replace(/[‘’]/g, "'")
        .replace(/[“”]/g, '"')
        .toLowerCase()
        .replace(/[^\x20-\x7e]/g, "")
        .replace(/\s+/g, " ")
        .trim();
}

// emoji-test.txt's fully-qualified emoji, skin tones left out, as
// { char, name, group } in the file's order.
export function parseEmoji(text) {
    const out = [];
    let group = "";
    for (const line of text.split("\n")) {
        const g = /^# group: (.*)$/.exec(line);
        if (g) {
            group = g[1].trim();
            continue;
        }
        const m = /^([0-9A-F ]+?)\s*; fully-qualified\s*# (\S+) E\d+\.\d+ (.*)$/.exec(line);
        if (!m || group === "Component" || /skin tone/.test(m[3])) {
            continue;
        }
        const char = String.fromCodePoint(...m[1].trim().split(/\s+/).map(h => parseInt(h, 16)));
        out.push({ char, name: plainName(m[3]), group });
    }
    return out;
}

// UnicodeData.txt's graphic characters in BLOCKS, as { char, name, group }.
// Within a block, lowercase letters come before capitals, so `e acute`
// offers é first.
export function parseSymbols(text, skip) {
    const names = new Map();
    for (const line of text.split("\n")) {
        const f = line.split(";");
        if (f.length < 3) {
            continue;
        }
        const cp = parseInt(f[0], 16);
        // Controls, marks, separators and unassigned have no glyph to pick.
        if (f[1].startsWith("<") || /^(C|M|Z)/.test(f[2])) {
            continue;
        }
        names.set(cp, f[1]);
    }
    const out = [];
    for (const [first, last, group] of BLOCKS) {
        const block = [];
        for (let cp = first; cp <= last; cp++) {
            const name = names.get(cp);
            if (name === undefined) {
                continue;
            }
            const char = String.fromCodePoint(cp);
            if (skip.has(char)) {
                continue;
            }
            block.push({ char, name: plainName(name), group, capital: /\bCAPITAL\b/.test(name) });
        }
        block.sort((a, b) => Number(a.capital) - Number(b.capital));
        for (const { char, name, group: g } of block) {
            out.push({ char, name, group: g });
        }
    }
    return out;
}

// The whole file: the symbols, then the emoji.
export function generate(emojiTest, unicodeData) {
    const emoji = parseEmoji(emojiTest);
    // An emoji's bare code point (without U+FE0F) is the symbol it shows as.
    const skip = new Set(emoji.map(e => e.char.replace(/️/g, "")));
    const version = /^# Version: (\S+)/m.exec(emojiTest)?.[1] ?? "unknown";
    const rows = parseSymbols(unicodeData, skip).concat(emoji);
    const header = [
        `# The picker's characters (tide SPEC.md §8.4): character, name, group.`,
        `# Generated by shell/chars/generate.mjs from Unicode ${version}'s`,
        `# emoji-test.txt and UnicodeData.txt. Don't edit; regenerate.`,
        `# Unicode data: Copyright (c) Unicode, Inc.`,
        `# Distributed under the Unicode License v3; see LICENSE-UNICODE.`,
    ];
    return header.concat(rows.map(r => `${r.char}\t${r.name}\t${r.group}`)).join("\n") + "\n";
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    if (process.argv.length !== 4) {
        console.error("usage: generate.mjs EMOJI_TEST UNICODE_DATA > chars.tsv");
        process.exit(2);
    }
    process.stdout.write(generate(readFileSync(process.argv[2], "utf8"), readFileSync(process.argv[3], "utf8")));
}
